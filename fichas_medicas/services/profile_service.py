"""Generación de perfiles estáticos HTML desde la proyección consentida."""

from __future__ import annotations

import re
from pathlib import Path
from string import Template

from fichas_medicas.config.paths import profiles_directory
from fichas_medicas.security.sanitization import escape_html, telephone_href
from fichas_medicas.security.validation import ValidationError
from fichas_medicas.services.patient_service import PatientService

UUID_PATTERN = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$")


class ProfileService:
    def __init__(self, patient_service: PatientService, output_dir: Path | str | None = None) -> None:
        self.patient_service = patient_service
        self.output_dir = Path(output_dir).expanduser().resolve() if output_dir else profiles_directory()

    def generate(self, patient_id: int) -> Path | None:
        patient = self.patient_service.repository.get(patient_id)
        if patient is None:
            raise KeyError(f"Expediente {patient_id} no encontrado.")
        public_data = self.patient_service.public_profile_data(patient_id)
        target = self._profile_path(patient.uuid)
        if public_data is None:
            target.unlink(missing_ok=True)
            return None

        html = self._render(public_data)
        self.output_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        try:
            self.output_dir.chmod(0o700)
        except OSError:
            pass
        temporary = target.with_suffix(".html.tmp")
        temporary.write_text(html, encoding="utf-8")
        try:
            temporary.chmod(0o600)
        except OSError:
            pass
        temporary.replace(target)
        self._write_stylesheet()
        return target

    def remove(self, patient_id: int) -> bool:
        patient = self.patient_service.repository.get(patient_id)
        if patient is None:
            # A logically deleted profile must also be removable. Resolve its UUID directly
            # through the repository's normal connection without exposing it to callers.
            with self.patient_service.repository.database.connect() as connection:
                row = connection.execute("SELECT uuid FROM patients WHERE id = ?", (patient_id,)).fetchone()
            if row is None:
                return False
            patient_uuid = row["uuid"]
        else:
            patient_uuid = patient.uuid
        path = self._profile_path(patient_uuid)
        existed = path.exists()
        path.unlink(missing_ok=True)
        return existed

    def remove_all(self) -> int:
        """Elimina perfiles HTML generados y su CSS, sin tocar archivos ajenos."""
        if not self.output_dir.exists():
            return 0
        removed = 0
        for path in self.output_dir.iterdir():
            if path.name == "styles.css" or UUID_PATTERN.fullmatch(path.stem) and path.suffix == ".html":
                if path.is_file() or path.is_symlink():
                    path.unlink(missing_ok=True)
                    removed += 1
        return removed

    def _profile_path(self, patient_uuid: str) -> Path:
        # UUIDv4 is generated by the application; restricting the name prevents path traversal.
        if not UUID_PATTERN.fullmatch(patient_uuid):
            raise ValidationError("Identificador de expediente no válido para crear el perfil.")
        return self.output_dir / f"{patient_uuid}.html"

    def _render(self, data: dict[str, object]) -> str:
        template_text = (
            Path(__file__).parents[1] / "templates" / "medical_profile.html"
        ).read_text(encoding="utf-8")
        sections: list[str] = []
        name = _text(data.get("full_name")) or "Persona"
        birth = _text(data.get("date_of_birth"))
        details = f'<div class="hero-details"><span>Ficha de emergencia</span>'
        if birth:
            details += f'<span>Fecha de nacimiento <strong>{escape_html(birth)}</strong></span>'
        details += "</div>"

        blood = _text(data.get("blood_type"))
        blood_card = ""
        if blood:
            blood_card = (
                '<section class="card blood-card" aria-label="Tipo de sangre">'
                '<div><p class="card-label"><span class="label-icon" aria-hidden="true">+</span>'
                "Tipo de sangre</p>"
                f'<div class="blood-value">{escape_html(blood)}</div></div>'
                '<span class="blood-symbol" aria-hidden="true">+</span></section>'
            )

        allergies = _text(data.get("allergies"))
        allergy_card = ""
        if allergies:
            allergy_card = (
                '<section class="card allergy-card" aria-labelledby="allergies-heading">'
                '<h2 class="card-label" id="allergies-heading">'
                '<span class="label-icon" aria-hidden="true">!</span>Alergias</h2>'
                f'<p class="card-body">{escape_html(allergies)}</p></section>'
            )

        for field, title, icon in (
            ("conditions", "Padecimientos", "＋"),
            ("medications", "Medicamentos", "Rx"),
            ("additional_information", "Información adicional", "i"),
        ):
            value = _text(data.get(field))
            if value:
                sections.append(
                    f'<section class="card card-wide" aria-labelledby="section-{field}">'
                    f'<h2 class="card-label" id="section-{field}">'
                    f'<span class="label-icon" aria-hidden="true">{icon}</span>{title}</h2>'
                    f'<p class="card-body">{escape_html(value)}</p></section>'
                )

        emergency = self._emergency_section(data)
        substitutions = {
            "full_name": escape_html(name),
            "hero_details": details,
            "blood_type_card": blood_card,
            "allergies_card": allergy_card,
            "medical_sections": "\n      ".join(sections),
            "emergency_section": emergency,
        }
        return Template(template_text).substitute(substitutions)

    def _emergency_section(self, data: dict[str, object]) -> str:
        contacts = []
        for index in range(1, 4):
            suffix = "" if index == 1 else f"_{index}"
            name = _text(data.get(f"emergency_contact{suffix}_name"))
            relationship = _text(data.get(f"emergency_contact{suffix}_relationship"))
            phone = _text(data.get(f"emergency_contact{suffix}_phone"))
            if any((name, relationship, phone)):
                contacts.append((index, name, relationship, phone))
        if not contacts:
            return ""
        rendered_contacts = []
        for index, name, relationship, phone in contacts:
            rows = []
            for label, value in (("Nombre", name), ("Parentesco", relationship), ("Teléfono", phone)):
                if value:
                    rows.append(
                        f'<div class="contact-item"><dt>{label}</dt><dd>{escape_html(value)}</dd></div>'
                    )
            call_link = ""
            if phone:
                href = escape_html(telephone_href(phone))
                call_link = f'<a class="call-link" href="{href}">Llamar al contacto {index} <span aria-hidden="true">↗</span></a>'
            rendered_contacts.append(
                f'<div class="emergency-contact"><h3>Contacto {index}</h3>'
                f'<dl class="contact-list">{"".join(rows)}</dl>{call_link}</div>'
            )
        return (
            '<section class="card card-wide" aria-labelledby="emergency-heading">'
            '<h2 class="card-label" id="emergency-heading">'
            '<span class="label-icon" aria-hidden="true">☎</span>Contactos de emergencia</h2>'
            f'{"".join(rendered_contacts)}</section>'
        )

    def _write_stylesheet(self) -> None:
        source = Path(__file__).parents[1] / "templates" / "styles.css"
        destination = self.output_dir / "styles.css"
        temporary = destination.with_suffix(".css.tmp")
        temporary.write_bytes(source.read_bytes())
        try:
            temporary.chmod(0o600)
        except OSError:
            pass
        temporary.replace(destination)


def _text(value: object) -> str:
    if value is None:
        return ""
    if not isinstance(value, str):
        raise ValidationError("La proyección de perfil contiene un campo que no es texto.")
    return value.strip()
